test_that("web report is standalone and escapes supplied content", {
  skip_if_not_installed("htmltools")
  skip_if_not_installed("ggplot2")
  skip_if_not_installed("knitr")
  table <- data.frame(Item = c("문항 | <Q1>", "</textarea><script>bad()</script>"),
                       Loading = c(.85, .72), check.names = FALSE)
  plot <- ggplot2::ggplot(data.frame(x = 1:2, y = c(.85, .72)),
                           ggplot2::aes(x, y)) + ggplot2::geom_col()
  path <- .cfa2_web_report(list("Loadings" = table, "HTMT" = NULL),
                             "F =~ Q1 + Q2\n# </textarea><script>bad()</script>",
                             plot, c("Q1", "Q2"))
  on.exit(unlink(path), add = TRUE)
  html <- paste(readLines(path, encoding = "UTF-8", warn = FALSE), collapse = "\n")
  expect_true(file.exists(path))
  expect_match(html, 'id="download-html"', fixed = TRUE)
  expect_match(html, 'id="download-md"', fixed = TRUE)
  expect_match(html, 'class="copy-table"', fixed = TRUE)
  expect_match(html, 'data:image/png;base64,', fixed = TRUE)
  expect_match(html, '&amp;#124;', fixed = TRUE)
  expect_match(html, '&lt;/textarea&gt;&lt;script&gt;bad()', fixed = TRUE)
  expect_false(grepl('<script>bad()', html, fixed = TRUE))
  expect_match(html, 'Not computed / unavailable.', fixed = TRUE)
  expect_false(grepl('<script src=', html, fixed = TRUE))
})

test_that("default web output opens all results while web FALSE preserves the selected output", {
  skip_if_not_installed("lavaan")
  skip_if_not_installed("semTools")
  skip_if_not_installed("semPlot")
  skip_if_not_installed("semptools")
  skip_if_not_installed("kableExtra")
  skip_if_not_installed("htmltools")
  fit <- lavaan::cfa("visual =~ x1 + x2 + x3\ntextual =~ x4 + x5 + x6\nspeed =~ x7 + x8 + x9",
                       data = lavaan::HolzingerSwineford1939)
  opened <- character()
  old <- options(browser = function(url, ...) { opened <<- c(opened, url) })
  on.exit(options(old), add = TRUE)
  selected <- cfa2(fit, type = "loadings_bar", web = FALSE)
  expect_s3_class(selected, "ggplot")
  expect_length(opened, 0L)
  expect_true(formals(cfa2)$web)
  result <- withVisible(cfa2(fit, type = "loadings_bar", dis.sort = FALSE))
  path <- attr(result$value, "web_file")
  on.exit(unlink(path), add = TRUE)
  expect_false(result$visible)
  expect_type(result$value, "list")
  expect_true(all(c("model", "model_fit", "loadings_Bar", "variable_order") %in% names(result$value)))
  expect_length(opened, 1L)
  expect_true(file.exists(path))
  html <- paste(readLines(path, encoding = "UTF-8", warn = FALSE), collapse = "\n")
  expect_match(html, '10 Item loadings / CR / AVE', fixed = TRUE)
  expect_match(html, 'download="cfa2-factor-loadings.png"', fixed = TRUE)
  expect_match(html, 'download="cfa2-model-unstandardized.png"', fixed = TRUE)
  expect_match(html, 'download="cfa2-model-standardized.png"', fixed = TRUE)
  expect_match(html, 'data-copy-target="model-code"', fixed = TRUE)
  expect_match(html, 'data-copy-target="diagram-code-unstandardized"', fixed = TRUE)
  expect_match(html, 'data-copy-target="diagram-code-standardized"', fixed = TRUE)
  order_at <- regexpr('<h2>Variable order</h2>', html, fixed = TRUE)[1]
  unstd_at <- regexpr('download="cfa2-model-unstandardized.png"', html, fixed = TRUE)[1]
  std_at <- regexpr('download="cfa2-model-standardized.png"', html, fixed = TRUE)[1]
  expect_true(order_at < unstd_at && unstd_at < std_at)
  expect_match(html, 'whatLabels = "est"', fixed = TRUE)
  expect_match(html, 'whatLabels = "std"', fixed = TRUE)
  expect_match(html, 'semPaths2(', fixed = TRUE)
  expect_equal(result$value$variable_order, paste0("x", 1:9))
  expect_error(cfa2(fit, web = NA), "web must be TRUE or FALSE", fixed = TRUE)
})


test_that("semPaths2 diagram scales, supports overrides, and preserves graphics devices", {
  skip_if_not_installed("lavaan")
  skip_if_not_installed("semPlot")
  skip_if_not_installed("semptools")
  fit <- lavaan::cfa("visual =~ x1 + x2 + x3\ntextual =~ x4 + x5 + x6\nspeed =~ x7 + x8 + x9",
                       data = lavaan::HolzingerSwineford1939)
  before <- grDevices::dev.cur()
  image <- .cfa2_path_image(fit, path_args = list(curve = 2.5), fit_label = "fit_7f")
  expect_null(image$error)
  expect_match(image$uri, "^data:image/png;base64,")
  expect_equal(image$args$curve, 2.5)
  expect_equal(image$args$sizeMan, 5)
  expect_equal(image$args$sizeMan2, 2)
  expect_equal(image$args$sizeLat, 6)
  expect_equal(image$args$sizeLat2, 3)
  expect_match(image$code, "fit_7f", fixed = TRUE)
  expect_match(image$code, "curve = 2.5", fixed = TRUE)
  expect_equal(grDevices::dev.cur(), before)
  expect_error(.cfa2_path_image(fit, list(bad_argument = 1)), "Unknown semPaths2 argument")
  expect_error(cfa2(fit, path_args = list(1)), "path_args must be a named list")
})
